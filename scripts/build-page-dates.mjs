#!/usr/bin/env node
/**
 * Works out when each page last changed, from git history, and emits
 * src/lib/page-dates.generated.ts for the sitemap's <lastmod> dates.
 *
 * - A chapter's date is the last commit touching its folder under
 *   src/app/(tutorial)/ — its text, quiz and page.
 * - The homepage's date is the latest of every chapter, curriculum.ts (where
 *   a chapter is published) and the homepage's own files, so publishing a
 *   new chapter moves it.
 *
 * Vercel builds from a shallow clone, where the oldest commit it has looks
 * like it changed every file. The repo is public, so the script fetches the
 * rest of the history first. If that fails it emits no dates at all: a
 * sitemap without dates is better than one with wrong dates.
 */
import { execFileSync } from "node:child_process";
import { readdirSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, "..");
const CHAPTERS_DIR = "src/app/(tutorial)";
const OUTPUT = join(ROOT, "src/lib/page-dates.generated.ts");
const PUBLIC_REPO = "https://github.com/robennals/ai-explained.git";

function git(...args) {
  return execFileSync("git", args, { cwd: ROOT, encoding: "utf-8" }).trim();
}

function isShallow() {
  return git("rev-parse", "--is-shallow-repository") === "true";
}

/** Returns true when the full history is available. */
function ensureFullHistory() {
  try {
    if (!isShallow()) return true;
    git("fetch", "--quiet", "--unshallow", PUBLIC_REPO);
    return !isShallow();
  } catch (err) {
    console.warn(`page dates: couldn't fetch full git history (${err.message})`);
    return false;
  }
}

/** ISO date of the last commit touching any of `paths`, or undefined. */
function lastChanged(...paths) {
  return git("log", "-1", "--format=%cI", "--", ...paths) || undefined;
}

function latest(dates) {
  const known = dates.filter(Boolean).sort();
  return known[known.length - 1];
}

/** Map from URL path ("/", "/neurons") to ISO date. */
function computeDates() {
  const dates = {};
  const slugs = readdirSync(join(ROOT, CHAPTERS_DIR), { withFileTypes: true })
    .filter((d) => d.isDirectory())
    .map((d) => d.name);
  for (const slug of slugs) {
    const date = lastChanged(`${CHAPTERS_DIR}/${slug}`);
    if (date) dates[`/${slug}`] = date;
  }
  dates["/educators"] = lastChanged("src/app/educators");
  dates["/"] = latest([
    ...Object.values(dates),
    lastChanged("src/lib/curriculum.ts", "src/app/page.tsx", "src/components/home"),
  ]);
  return dates;
}

let dates = {};
try {
  if (ensureFullHistory()) dates = computeDates();
} catch (err) {
  console.warn(`page dates: couldn't read git history (${err.message})`);
}

writeFileSync(
  OUTPUT,
  [
    "// Generated by scripts/build-page-dates.mjs. Do not edit.",
    "// Maps a URL path to when that page last changed. Empty if git history",
    "// was unavailable at build time.",
    `export const pageDates: Record<string, string> = ${JSON.stringify(dates, null, 2)};`,
    "",
  ].join("\n"),
  "utf-8",
);
console.log(`page dates: wrote ${Object.keys(dates).length} dates`);
